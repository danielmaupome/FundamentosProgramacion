# La instrucción print despliega un mensaje en la pantalla.
print("Hola Mundo")

# Dicho mensaje puede ir entre comillas dobles " o comillas simples ', pero nunca combinados.
print('Mensaje con Comillas Simples')

# Eso si, puedo usar comillas simples dentro de comillas dobles, para que salga dentro del mensaje.
print("Bienvenidos a la mejor clase: 'Programación'")

# Si necesito que mi impresión lleve comillas dobles, debo usar \" en la apertura y clausura.
print("Frase del día \"El único código que no tiene errores es el que nunca se escribe.\"")

# Podemos también usar caracteres de escape. por ejemplo, el \n significa salto de línea.
print("Buen Día \nGracias por tu visita.")

# \t significa tabulador, es decir, un espaciado dentro de la misma línea.

print("Apellido Paterno \t* Apellido Materno \t* Nombre(s)")
print("Maupomé \t\t* Rosales \t\t* Daniel Arturo")

